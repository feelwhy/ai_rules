#!/usr/bin/env python3
"""Generate Cursor rules and Claude Code files from src/*.md (+ optional overrides/).

Cursor: .cursor/rules/*.mdc and docs/rules.md.
Claude: CLAUDE.md holds apply:always rules. apply:agent rules become skills
under .claude/skills/. On the faOtools hub this also replaces the temporary
project CLAUDE.md files and links each project at its own skills.

Usage:
  python3 tools/sync_rules.py          # write generated files
  python3 tools/sync_rules.py --check  # exit 1 if generated output would drift
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
SRC_DIR = REPO_ROOT / "src"
OVERRIDES_DIR = REPO_ROOT / "overrides"
OUT_RULES = REPO_ROOT / ".cursor" / "rules"
AGENTS_PATH = REPO_ROOT / "docs" / "rules.md"
CLAUDE_PATH = REPO_ROOT / "CLAUDE.md"
SKILLS_DIR = REPO_ROOT / ".claude" / "skills"
# Cursor loads every file named AGENTS.md (the root one, and nested ones) with alwaysApply.
# The generated copy must not use that name.
MARKER = "generated by sync_rules.py"

FRONTMATTER_RE = re.compile(r"^---\n(.*?)\n---\n(.*)$", re.DOTALL)


def parse_frontmatter(path: Path, text: str) -> tuple[dict[str, str], str]:
    match = FRONTMATTER_RE.match(text)
    if not match:
        raise SystemExit(f"{path}: missing YAML frontmatter")
    meta: dict[str, str] = {}
    for line in match.group(1).splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if ":" not in line:
            raise SystemExit(f"{path}: bad frontmatter line: {line!r}")
        key, val = line.split(":", 1)
        meta[key.strip()] = val.strip().strip("\"'")
    return meta, match.group(2).lstrip("\n")


def parse_md(path: Path) -> tuple[dict[str, str], str]:
    return parse_frontmatter(path, path.read_text(encoding="utf-8"))


def load_sources() -> list[tuple[str, dict[str, str], str]]:
    if not SRC_DIR.is_dir():
        raise SystemExit(f"missing {SRC_DIR}")
    items: list[tuple[str, dict[str, str], str]] = []
    for path in sorted(SRC_DIR.glob("*.md")):
        meta, body = parse_md(path)
        rid = meta.get("id") or path.stem
        override = OVERRIDES_DIR / f"{rid}.md"
        if override.is_file():
            ometa, obody = parse_md(override)
            body = obody
            meta = {**meta, **{k: v for k, v in ometa.items() if k != "id"}}
        items.append((rid, meta, body))
    return items


def render_mdc(meta: dict[str, str], body: str) -> str:
    apply = meta.get("apply", "agent")
    always = "true" if apply == "always" else "false"
    description = meta.get("description", meta.get("id", "rule"))
    lines = [
        "---",
        f"description: {description}",
        f"alwaysApply: {always}",
        "---",
        "",
        body.rstrip() + "\n",
    ]
    return "\n".join(lines)


def render_agents(items: list[tuple[str, dict[str, str], str]]) -> str:
    parts = [
        f"# {REPO_ROOT.name}",
        "",
        f"Generated from `src/*.md` by `tools/sync_rules.py`. Do not edit by hand.",
        "",
    ]
    for rid, _meta, body in items:
        title = _meta.get("description", rid)
        parts.append(f"## {rid}")
        parts.append("")
        parts.append(f"_{title}_")
        parts.append("")
        parts.append(body.rstrip())
        parts.append("")
    return "\n".join(parts).rstrip() + "\n"


def skill_prefix() -> str:
    return {"ai_rules": "ai-rules", "ai_rules_fao": "fao"}.get(REPO_ROOT.name, REPO_ROOT.name.replace("_", "-"))


def skill_name(rid: str) -> str:
    return f"{skill_prefix()}-{rid}"


def render_claude(items: list[tuple[str, dict[str, str], str]]) -> str:
    parts = [
        f"# {REPO_ROOT.name}",
        "",
        "Generated from `src/*.md` by `tools/sync_rules.py`. Do not edit by hand.",
        "Always-on rules only. Procedures are skills in `.claude/skills/`.",
        "",
    ]
    for _rid, meta, body in items:
        if meta.get("apply", "agent") != "always":
            continue
        parts.append(body.rstrip())
        parts.append("")
    return "\n".join(parts).rstrip() + "\n"


def render_skill(rid: str, meta: dict[str, str], body: str) -> str:
    description = meta.get("description", rid).replace('"', "'")
    return (
        "---\n"
        f"name: {skill_name(rid)}\n"
        f"description: {description}\n"
        "---\n\n"
        f"<!-- {MARKER} -->\n\n"
        f"{body.rstrip()}\n"
    )


def skill_map(items: list[tuple[str, dict[str, str], str]]) -> dict[str, str]:
    skills: dict[str, str] = {}
    for rid, meta, body in items:
        if meta.get("apply", "agent") == "always":
            continue
        skills[skill_name(rid)] = render_skill(rid, meta, body)
    return skills


def agents_md_files() -> list[Path]:
    found: list[Path] = []
    for path in REPO_ROOT.rglob("AGENTS.md"):
        if ".git" in path.parts:
            continue
        found.append(path)
    return found


def token_count(text: str) -> int:
    return len(text) // 4


def expanded_tokens(path: Path) -> int:
    """Tokens Claude loads from a CLAUDE.md, following one level of @imports."""
    if not path.is_file():
        return 0
    text = path.read_text(encoding="utf-8")
    chunks = [text]
    for line in text.splitlines():
        if not line.startswith("@"):
            continue
        included = (path.parent / line[1:].strip()).resolve()
        if included.is_file():
            chunks.append(included.read_text(encoding="utf-8"))
    return token_count("\n".join(chunks))


def hub_root() -> Path | None:
    parent = REPO_ROOT.parent
    if (parent / "ai_rules").is_dir() and (parent / "ai_rules_fao").is_dir() and (parent / "life").is_dir():
        return parent
    return None


def life_root(hub: Path) -> Path | None:
    """The life project root: symlinks to its repos, universal skills only."""
    root = hub.parent / "Life"
    return root if root.is_dir() else None


def hub_claude_text() -> str:
    return (
        "# faotools\n\n"
        "Generated by `tools/sync_rules.py`. Do not edit by hand.\n"
        "Always-on rules for this project. Procedures are skills in `.claude/skills/`.\n\n"
        "@ai_rules/CLAUDE.md\n"
        "@ai_rules_fao/CLAUDE.md\n"
    )


def life_claude_text() -> str:
    return (
        "# life\n\n"
        "Generated by `tools/sync_rules.py`. Do not edit by hand.\n"
        "Universal always-on rules only. faOtools rules are not loaded here.\n\n"
        "@../ai_rules/CLAUDE.md\n"
    )


def project_files() -> dict[Path, str]:
    hub = hub_root()
    if hub is None:
        return {}
    files = {
        hub / "CLAUDE.md": hub_claude_text(),
        hub / "life" / "CLAUDE.md": life_claude_text(),
    }
    return files


def project_links() -> dict[Path, Path]:
    hub = hub_root()
    if hub is None:
        return {}
    links: dict[Path, Path] = {}

    def add(dest_dir: Path, skill_root: Path) -> None:
        if not skill_root.is_dir():
            return
        for skill in sorted(skill_root.iterdir()):
            if (skill / "SKILL.md").is_file():
                links[dest_dir / skill.name] = skill

    add(hub / ".claude" / "skills", hub / "ai_rules" / ".claude" / "skills")
    add(hub / ".claude" / "skills", hub / "ai_rules_fao" / ".claude" / "skills")
    life = life_root(hub)
    if life is not None:
        add(life / ".claude" / "skills", hub / "ai_rules" / ".claude" / "skills")
    return links


def build() -> tuple[dict[str, str], str, str, dict[str, str]]:
    items = load_sources()
    return (
        {rid: render_mdc(meta, body) for rid, meta, body in items},
        render_agents(items),
        render_claude(items),
        skill_map(items),
    )


def write_skills(skills: dict[str, str]) -> None:
    SKILLS_DIR.mkdir(parents=True, exist_ok=True)
    for existing in list(SKILLS_DIR.iterdir()):
        marker = existing / "SKILL.md"
        if existing.is_dir() and existing.name not in skills and marker.is_file():
            if MARKER in marker.read_text(encoding="utf-8"):
                marker.unlink()
                existing.rmdir()
    for name, content in skills.items():
        dest = SKILLS_DIR / name
        dest.mkdir(parents=True, exist_ok=True)
        (dest / "SKILL.md").write_text(content, encoding="utf-8")


def stale_skill_links(links: dict[Path, Path]) -> list[Path]:
    """Symlinks left behind after a skill stopped being generated."""
    hub = hub_root()
    if hub is None:
        return []
    roots = (
        (hub / "ai_rules" / ".claude" / "skills").resolve(),
        (hub / "ai_rules_fao" / ".claude" / "skills").resolve(),
    )
    keep = set(links)
    stale: list[Path] = []
    # hub/life/.claude/skills held the life links before ~/Life; clear them there too.
    dest_dirs = [hub / ".claude" / "skills", hub / "life" / ".claude" / "skills"]
    life = life_root(hub)
    if life is not None:
        dest_dirs.append(life / ".claude" / "skills")
    for dest_dir in dest_dirs:
        if not dest_dir.is_dir():
            continue
        for dest in dest_dir.iterdir():
            if not dest.is_symlink() or dest in keep:
                continue
            raw = dest.readlink()
            if not raw.is_absolute():
                raw = dest.parent / raw
            target = raw.resolve()
            if any(target == root or root in target.parents for root in roots):
                stale.append(dest)
    return stale


def write_links(links: dict[Path, Path]) -> None:
    for dest in stale_skill_links(links):
        dest.unlink()
    for dest, target in links.items():
        dest.parent.mkdir(parents=True, exist_ok=True)
        if dest.is_symlink() or dest.exists():
            if dest.is_symlink() and dest.resolve() == target.resolve():
                continue
            if dest.is_symlink():
                dest.unlink()
            else:
                raise SystemExit(f"{dest} exists and is not a symlink")
        dest.symlink_to(target)


def write_all(mdc_map: dict[str, str], agents: str, claude: str, skills: dict[str, str]) -> None:
    OUT_RULES.mkdir(parents=True, exist_ok=True)
    keep = set(mdc_map)
    for existing in OUT_RULES.glob("*.mdc"):
        if existing.stem not in keep:
            existing.unlink()
    for rid, content in mdc_map.items():
        (OUT_RULES / f"{rid}.mdc").write_text(content, encoding="utf-8")
    AGENTS_PATH.parent.mkdir(parents=True, exist_ok=True)
    AGENTS_PATH.write_text(agents, encoding="utf-8")
    CLAUDE_PATH.write_text(claude, encoding="utf-8")
    write_skills(skills)
    for stale in agents_md_files():
        stale.unlink()
    for path, content in project_files().items():
        path.write_text(content, encoding="utf-8")
    write_links(project_links())


def same(path: Path, content: str) -> bool:
    return path.is_file() and path.read_text(encoding="utf-8") == content


def check(mdc_map: dict[str, str], agents: str, claude: str, skills: dict[str, str]) -> int:
    drift = False
    if not same(AGENTS_PATH, agents):
        print(f"DRIFT: {AGENTS_PATH}", file=sys.stderr)
        drift = True
    if not same(CLAUDE_PATH, claude):
        print(f"DRIFT: {CLAUDE_PATH}", file=sys.stderr)
        drift = True
    for stale in agents_md_files():
        print(f"STALE: {stale} (Cursor injects every file named AGENTS.md)", file=sys.stderr)
        drift = True
    for rid, content in mdc_map.items():
        path = OUT_RULES / f"{rid}.mdc"
        if not same(path, content):
            print(f"DRIFT: {path}", file=sys.stderr)
            drift = True
    if OUT_RULES.is_dir():
        for existing in OUT_RULES.glob("*.mdc"):
            if existing.stem not in mdc_map:
                print(f"STALE: {existing}", file=sys.stderr)
                drift = True
    expected_dirs = set(skills)
    if SKILLS_DIR.is_dir():
        for existing in SKILLS_DIR.iterdir():
            marker = existing / "SKILL.md"
            if existing.is_dir() and existing.name not in expected_dirs and marker.is_file():
                if MARKER in marker.read_text(encoding="utf-8"):
                    print(f"STALE: {existing}", file=sys.stderr)
                    drift = True
    for name, content in skills.items():
        path = SKILLS_DIR / name / "SKILL.md"
        if not same(path, content):
            print(f"DRIFT: {path}", file=sys.stderr)
            drift = True
    for path, content in project_files().items():
        if not same(path, content):
            print(f"DRIFT: {path}", file=sys.stderr)
            drift = True
    expected = project_links()
    for dest in stale_skill_links(expected):
        print(f"STALE: {dest}", file=sys.stderr)
        drift = True
    for dest, target in expected.items():
        if not dest.is_symlink() or dest.resolve() != target.resolve():
            print(f"DRIFT: {dest}", file=sys.stderr)
            drift = True
    return 1 if drift else 0


def print_report(claude: str, skills: dict[str, str], before: dict[str, int]) -> None:
    always = token_count(claude)
    skill_tokens = sum(token_count(text) for text in skills.values())
    print(f"{REPO_ROOT.name} always-on tokens: {always}")
    print(f"{REPO_ROOT.name} skill tokens (not loaded every turn): {skill_tokens}")
    hub = hub_root()
    if hub is None:
        return
    after_hub = expanded_tokens(hub / "CLAUDE.md")
    after_life = expanded_tokens(hub / "life" / "CLAUDE.md")
    print(f"faotools always-on tokens before: {before.get('faotools', 0)}")
    print(f"faotools always-on tokens after: {after_hub}")
    print(f"life always-on tokens before: {before.get('life', 0)}")
    print(f"life always-on tokens after: {after_life}")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    hub = hub_root()
    before = {}
    if hub is not None:
        before["faotools"] = expanded_tokens(hub / "CLAUDE.md")
        before["life"] = expanded_tokens(hub / "life" / "CLAUDE.md")
    mdc_map, agents, claude, skills = build()
    if args.check:
        code = check(mdc_map, agents, claude, skills)
        print_report(claude, skills, before)
        return code
    write_all(mdc_map, agents, claude, skills)
    print(f"wrote {len(mdc_map)} rules → {OUT_RULES}")
    print(f"wrote {AGENTS_PATH}")
    print(f"wrote {CLAUDE_PATH}")
    print(f"wrote {len(skills)} skills → {SKILLS_DIR}")
    print_report(claude, skills, before)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
